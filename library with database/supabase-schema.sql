-- BookNest Library Management System - Supabase schema
-- Run once in Supabase Dashboard > SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'Student',
  email text not null unique,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text not null,
  isbn text unique,
  total_copies integer not null check (total_copies >= 1),
  available_copies integer not null check (available_copies >= 0 and available_copies <= total_copies),
  created_at timestamptz not null default now()
);

create table if not exists public.borrow_records (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id),
  book_id bigint not null references public.books(id),
  borrowed_at timestamptz not null default now(),
  due_date timestamptz not null,
  returned_at timestamptz,
  status text not null default 'Borrowed' check (status in ('Borrowed','Returned')),
  constraint borrow_return_consistency check (
    (status = 'Borrowed' and returned_at is null) or
    (status = 'Returned' and returned_at is not null)
  )
);

create unique index if not exists one_active_borrow_per_user_book
on public.borrow_records(user_id, book_id) where status = 'Borrowed';

-- Automatically create a student profile after Supabase Auth signup.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', 'Student'),
    new.email,
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- SECURITY DEFINER avoids RLS recursion when checking the current user's role.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.books enable row level security;
alter table public.borrow_records enable row level security;

drop policy if exists "profile read self or admin" on public.profiles;
create policy "profile read self or admin" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "books visible to signed-in users" on public.books;
create policy "books visible to signed-in users" on public.books
for select to authenticated using (true);

drop policy if exists "admins insert books" on public.books;
create policy "admins insert books" on public.books
for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "admins update books" on public.books;
create policy "admins update books" on public.books
for update to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

drop policy if exists "admins delete books" on public.books;
create policy "admins delete books" on public.books
for delete to authenticated using ((select public.is_admin()));

drop policy if exists "read own records or all as admin" on public.borrow_records;
create policy "read own records or all as admin" on public.borrow_records
for select to authenticated
using (user_id = (select auth.uid()) or (select public.is_admin()));

-- Borrow/return writes are performed only through these controlled RPC functions.
revoke insert, update, delete on public.borrow_records from anon, authenticated;
grant select on public.profiles, public.books, public.borrow_records to authenticated;
grant insert, update, delete on public.books to authenticated;
grant usage, select on sequence public.books_id_seq to authenticated;
grant update (full_name) on public.profiles to authenticated;

create or replace function public.borrow_book(p_book_id bigint)
returns uuid language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_record_id uuid;
begin
  if v_user_id is null then raise exception 'Please sign in first.'; end if;
  if (select public.is_admin()) then raise exception 'Admin accounts cannot borrow books.'; end if;

  update public.books
  set available_copies = available_copies - 1
  where id = p_book_id and available_copies > 0;

  if not found then raise exception 'This book is currently unavailable.'; end if;

  insert into public.borrow_records(user_id, book_id, due_date)
  values (v_user_id, p_book_id, now() + interval '14 days')
  returning id into v_record_id;

  return v_record_id;
exception when unique_violation then
  -- Rollback of this function call also restores the stock decrement.
  raise exception 'You already have this book borrowed.';
end;
$$;

create or replace function public.return_book(p_record_id uuid)
returns boolean language plpgsql security definer set search_path = ''
as $$
declare
  v_book_id bigint;
begin
  if auth.uid() is null then raise exception 'Please sign in first.'; end if;

  update public.borrow_records
  set status = 'Returned', returned_at = now()
  where id = p_record_id
    and status = 'Borrowed'
    and (user_id = auth.uid() or (select public.is_admin()))
  returning book_id into v_book_id;

  if not found then raise exception 'Active borrowing record not found or not permitted.'; end if;

  update public.books
  set available_copies = least(total_copies, available_copies + 1)
  where id = v_book_id;

  return true;
end;
$$;

revoke all on function public.borrow_book(bigint) from public;
revoke all on function public.return_book(uuid) from public;
grant execute on function public.borrow_book(bigint) to authenticated;
grant execute on function public.return_book(uuid) to authenticated;
grant execute on function public.is_admin() to authenticated;

